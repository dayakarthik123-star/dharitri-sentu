export function fetchParcelsInBBox(
  west: number,
  south: number,
  east: number,
  north: number
): CadastralParcelRecord[] {
  return CADASTRAL_PARCEL_RECORDS.filter((p) => {
    const [lat, lng] = p.centroid;
    return lng >= west && lng <= east && lat >= south && lat <= north;
  });
}

export function fetchParcelById(parcelOrListingId: string): CadastralParcelRecord | undefined {
  const norm = parcelOrListingId.trim().toLowerCase();
  return CADASTRAL_PARCEL_RECORDS.find(
    (p) =>
      p.parcel_id.toLowerCase() === norm ||
      p.listing_id.toLowerCase() === norm ||
      p.dag_number.toLowerCase() === norm ||
      p.ulpin.toLowerCase() === norm
  );
}

export function searchParcelsByDag(dagOrUlpinOrVillage: string): CadastralParcelRecord[] {
  const q = dagOrUlpinOrVillage.trim().toLowerCase();
  if (!q) return CADASTRAL_PARCEL_RECORDS;
  return CADASTRAL_PARCEL_RECORDS.filter(
    (p) =>
      p.dag_number.toLowerCase().includes(q) ||
      p.ulpin.toLowerCase().includes(q) ||
      p.patta_number.toLowerCase().includes(q) ||
      p.village_name.toLowerCase().includes(q) ||
      p.district_name.toLowerCase().includes(q) ||
      p.parcel_id.toLowerCase().includes(q) ||
      p.pattadar_name.toLowerCase().includes(q)
  );
}
