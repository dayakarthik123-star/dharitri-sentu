export function getMapTilerApiKey(): string {
  try {
    const winEnv = typeof window !== 'undefined' ? (window as any).__ENV : undefined;
    if (winEnv && typeof winEnv.VITE_MAPTILER_API_KEY === 'string') {
      return winEnv.VITE_MAPTILER_API_KEY.trim();
    }
    if (typeof import.meta !== 'undefined' && import.meta.env && import.meta.env.VITE_MAPTILER_API_KEY) {
      return String(import.meta.env.VITE_MAPTILER_API_KEY).trim();
    }
  } catch {
    // Ignore in environments without import.meta
  }
  return '1Er6BdS2HVkdpdxxG7dr';
}

export function isUsableMapTilerKey(key: string = getMapTilerApiKey()): boolean {
  const normalized = key.trim().toLowerCase();
  return Boolean(
    normalized &&
      normalized.length >= 8 &&
      normalized !== 'demo' &&
      !normalized.startsWith('your_') &&
      !normalized.includes('placeholder') &&
      !normalized.includes('replace_me') &&
      !normalized.includes('replace-me')
  );
}

